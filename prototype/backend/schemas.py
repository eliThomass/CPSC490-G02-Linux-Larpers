from datetime import datetime
from typing import Literal
from uuid import UUID

from pydantic import AwareDatetime, BaseModel, ConfigDict, Field


# Will check all incoming observations for validity and reject any that are invalid.
# This is to prevent bad data from being stored in the database.
class ObservationCreate(BaseModel):
    """Common Wifi/Bluetooth input with explicit units and missing-field behavior

    Nullable fields may be null or omitted; metadata defaults to an empty object.
    The backend generates observation_id and received_at when storing the record.
    """

    scanner_id: UUID = Field(description="ID of the scanner that captured the signal.")
    session_id: UUID = Field(description="ID of the collection or testing period.")
    device_id: UUID | None = Field(
        default=None,
        description="Tracked device ID, if already associated with this capture.",
    )
    captured_at: AwareDatetime = Field(
        description="Time the scanner captured the signal."
    )
    protocol: Literal["wifi", "bluetooth"]
    observed_address: str | None = Field(
        default=None,
        description="Address observed in the capture; (Not permanent device id)",
    )
    address_type: str | None = Field(
        default=None, description="Type of observed address, if available (ex, bssid)"
    )
    rssi_dbm: int | None = Field(
        default=None,
        description="Received signal strength in dBm, if available. Not percentage",
    )
    signal_percent: int | None = Field(
        default=None,
        ge=0,
        le=100,
        description="Signal percentage (0-100), if supplied by the source. Not converted from RSSI",
    )
    metadata: dict = Field(
        default_factory=dict,
        description="Additional capture metadata, empty obj if unavailable",
    )


class ObservationRead(BaseModel):
    """Common Wifi/Bluetooth output with explicit units and missing-field behavior

    Nullable fields are returned as null; unavailable metadata is an empty object.
    Includes the observation_id and received_at generated by the backend.
    """

    model_config = ConfigDict(from_attributes=True)

    observation_id: UUID = Field(description="Observation ID generated by the backend.")
    scanner_id: UUID = Field(description="ID of the scanner that captured the signal.")
    session_id: UUID = Field(description="ID of the collection or testing period.")
    device_id: UUID | None = Field(
        description="Tracked device ID, if already associated with this capture."
    )
    captured_at: datetime = Field(description="Time the scanner captured the signal.")
    received_at: datetime = Field(
        description="Time the backend inserted the observation, generated in UTC."
    )
    protocol: str = Field(description="Captured wireless protocol.")
    observed_address: str | None = Field(
        description="Address observed in the capture; (Not permanent device id)"
    )
    address_type: str | None = Field(
        description="Type of observed address, if available (ex, bssid)"
    )
    rssi_dbm: int | None = Field(
        description="Received signal strength in dBm, if available. Not percentage"
    )
    signal_percent: int | None = Field(
        description="Signal percentage (0-100), if supplied by the source. Not converted from RSSI"
    )
    metadata: dict = Field(
        validation_alias="metadata_",
        description="Additional capture metadata, empty obj if unavailable",
    )
